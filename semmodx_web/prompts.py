def parse_rename_json(text):
    """Parse the model's rename reply, tolerating prose or code fences."""
    if not text:
        return {}
    t = text.strip()
    # Strip ```json ... ``` fences if present.
    m = re.search(r"```(?:json)?\s*(.+?)```", t, re.DOTALL)
    if m:
        t = m.group(1).strip()
    try:
        obj = json.loads(t)
    except Exception:
        # Last resort: grab the outermost {...}
        m = re.search(r"\{.*\}", t, re.DOTALL)
        if not m:
            return {}
        try:
            obj = json.loads(m.group(0))
        except Exception:
            return {}
    if not isinstance(obj, dict):
        return {}
    # Keep only str->str pairs that look like identifiers.
    out = {}
    for k, v in obj.items():
        if not isinstance(k, str) or not isinstance(v, str):
            continue
        if not re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", v):
            continue
        out[k] = v
    return out


def build_decorated_comment(module_name, func_name, response, existing):
    """Reproduce ModuleAnalysisHandler.add_function_comment().

    The fence-cleaning regex makes repeated runs idempotent instead of stacking
    duplicate blocks.
    """
    existing = existing or ""
    cleaned = re.sub(
        r"----- Comment generated by SemModX -----.*?----------------------------------------",
        "",
        existing,
        flags=re.DOTALL,
    )
    return (
        "----- Comment generated by SemModX -----\n\n"
        "\u6a21\u5757: %s\n\u51fd\u6570: %s\n\n"
        "\u5206\u6790\u7ed3\u679c:\n%s\n\n"
        "----------------------------------------\n\n%s"
        % (module_name, func_name, response.strip(), cleaned.strip())
    )


